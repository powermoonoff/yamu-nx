// Журнал «почему закрылись»: приложение и модуль собраны без исключений, поэтому нехватка памяти
// или abort() закрывают их молча — Atmosphère отчёт о краше не пишет. Здесь мы успеваем записать
// причину, занятую память и адрес вызова (для addr2line). Для записи в этот момент держим запас памяти.
#pragma once

// Открыть журнал (дописывать в конец; больше 64 КБ — начать заново) и поставить обработчик нехватки памяти.
// Для abort() нужен ещё -Wl,--wrap=abort при сборке.
void crashLogInit(const char *path, const char *who);

// Обычная строка журнала с временем от включения консоли; сразу на карту.
void crashLog(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

// Сколько КБ кучи занято и свободно (mallinfo).
void heapKb(unsigned &usedKb, unsigned &freeKb);
